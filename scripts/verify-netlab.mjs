// MyNETLAB pod portal + the router takeover screen. node scripts/verify-netlab.mjs [url] [outDir]
import { chromium } from 'playwright-core';
import fs from 'node:fs';
const url = process.argv[2] || 'http://localhost:5194/cyber-office/';
const out = process.argv[3] || 'docs/proof/netlab';
fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1366, height: 800 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
let pass = 0; let fail = 0;
const check = (ok, label) => { if (ok) pass += 1; else fail += 1; console.log(`${ok ? 'PASS' : 'FAIL'} ${label}`); };
await page.goto(url + '?v=' + Date.now());
await page.waitForFunction(() => window.__game?.scene?.isActive('Title'), null, { timeout: 20000 });
await page.waitForTimeout(400); await page.keyboard.press('t');
await page.waitForFunction(() => window.__game.scene.isActive('Competitions'));
await page.locator('.comp-card[data-mode="ccdc"]').click();
await page.waitForFunction(() => window.__game.scene.isActive('CcdcLab'));
await page.locator('.ccx-radio', { hasText: 'Under Pressure' }).click();
await page.locator('.ccx-btn.primary').click();
await page.waitForSelector('.jb-taskbar');
await page.locator('.jb-tb-app[data-open="mynetlab"]').click();
const W = page.locator('.jb-win[data-win="mynetlab"]');
await W.locator('.mnl-topo').waitFor();
check((await W.locator('.mnl-crumbs').innerText()).includes('Reservation 24144'), 'breadcrumb MyNETLAB > CCDC State Pod 16 > Reservation 24144 > 2027 State');
check(await W.locator('.mnl-btn').count() === 13, `13 buttons (Topology, Content, Status + 10 VMs): ${await W.locator('.mnl-btn').count()}`);
await page.screenshot({ path: `${out}/topology.png` });
// Splunk console: capitals are lost until the keyboard layout is fixed.
await W.locator('.mnl-btn[data-view="splunk"] .mnl-btn-main').click();
await W.locator('.mnl-frame .tv-input').fill('echo ZipsBlue');
await W.locator('.mnl-frame .tv-input').press('Enter');
const t1 = await W.locator('.mnl-frame').innerText();
check(/echo zipsblue/.test(t1) && !/ZipsBlue/.test(t1), 'default layout: capitals arrive in lower case');
await W.locator('.mnl-btn[data-view="splunk"] .mnl-caret').click();
await W.locator('.mnl-mi[data-mi="keyboard:"]').click();
await W.locator('.mnl-frame .tv-input').fill('echo ZipsBlue');
await W.locator('.mnl-frame .tv-input').press('Enter');
check((await W.locator('.mnl-frame').innerText()).includes('echo ZipsBlue'), 'en-us layout: capitals work');
await page.screenshot({ path: `${out}/splunk-console.png` });
// AD console is the Windows desktop.
await W.locator('.mnl-btn[data-view="dc"] .mnl-btn-main').click();
check(await W.locator('.mnl-btn.on[data-view="dc"]').count() === 1 && await W.locator('.mnl-con-win').count() === 1, '2022 AD button turns red and shows the Windows console');
await page.screenshot({ path: `${out}/ad-console.png` });
// Reboot the router from the portal: boot menu, then option 1 = the takeover animation.
await W.locator('.mnl-btn[data-view="vyos"] .mnl-caret').click();
await W.locator('.mnl-mi[data-mi="power"]').click();
await W.locator('.tk-text[data-mode="menu"]').waitFor({ timeout: 4000 });
check((await W.locator('.tk-text').innerText()).includes('1. virtio-scsi Drive QEMU QEMU HARDDISK 2.5+'), 'reboot lands on the SeaBIOS boot menu');
await page.screenshot({ path: `${out}/vyos-bootmenu.png` });
await W.locator('.tk-key[data-key="4"]').click();
check((await W.locator('.tk-text').innerText()).includes('No configuration methods succeeded'), 'option 4: iPXE fails');
await page.screenshot({ path: `${out}/vyos-ipxe.png` });
await W.locator('.tk').press('Enter');
await W.locator('.tk-key[data-key="1"]').click();
await W.locator('.tk-canvas').waitFor();
await page.waitForTimeout(700);
check(await W.locator('.tk-canvas').count() === 1, 'option 1: the console is replaced by the looping animation');
await page.screenshot({ path: `${out}/vyos-takeover.png` });
const down = await page.evaluate(() => { const s = window.__game.scene.getScene('CcdcLab').state; return Object.values(s.services).filter((x) => x.state !== 'up').length; });
check(down >= 17, `every routed service is down (${down})`);
check(errors.length === 0, `no console errors ${errors.slice(0, 2).join(' | ')}`);
console.log(`${pass} passed, ${fail} failed`);
await browser.close();
process.exit(fail ? 1 : 0);
