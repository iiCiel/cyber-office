// Live Nov 14 events in the Invitational replay: goose wall broadcast in an open PuTTY, the teammate bulk reset,
// the router console takeover. Jumps the round clock. node scripts/verify-live.mjs [url] [outDir]
import { chromium } from 'playwright-core';
import fs from 'node:fs';
const url = process.argv[2] || 'http://localhost:5194/cyber-office/';
const out = process.argv[3] || 'docs/proof/underpressure';
fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1366, height: 800 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
let pass = 0; let fail = 0;
const check = (ok, label) => { if (ok) pass += 1; else fail += 1; console.log(`${ok ? 'PASS' : 'FAIL'} ${label}`); };
await page.goto(url + '?v=' + Date.now());
await page.waitForFunction(() => window.__game?.scene?.isActive('Title'), null, { timeout: 20000 });
await page.waitForTimeout(400); await page.keyboard.press('t');
await page.waitForFunction(() => window.__game.scene.isActive('Competitions'));
await page.locator('.comp-card[data-mode="ccdc"]').click();
await page.waitForFunction(() => window.__game.scene.isActive('CcdcLab'));
await page.locator('.ccx-radio', { hasText: 'Under Pressure' }).click();
await page.locator('.ccx-btn.primary').click();
await page.waitForSelector('.jb-taskbar');
const jump = (sec) => page.evaluate(async (t) => { const m = await import('/cyber-office/src/game/ccdcEngine.js'); m.tickTo(window.__game.scene.getScene('CcdcLab').state, t); }, sec);
await page.locator('.jb-tb-app[data-open="ssh-ecom"]').click();
await page.locator('.jb-win[data-win="ssh-ecom"] .tv-input').waitFor();
await jump(205); await page.waitForTimeout(1500);
const ecom = await page.locator('.jb-win[data-win="ssh-ecom"]').innerText();
check(ecom.includes('you are now the incident'), 'goose wall broadcast printed in the open Rocky PuTTY');
check(ecom.includes('Broadcast message from root@ecom'), 'wall header');
await page.screenshot({ path: `${out}/12-goose-wall.png` });
await page.evaluate(() => { window.__toasts = []; new MutationObserver((ms) => { for (const m of ms) for (const n of m.addedNodes) if (n.classList?.contains('jb-toast')) window.__toasts.push(n.innerText); }).observe(document.querySelector('.jb-toasts'), { childList: true }); });
await jump(605); await page.waitForTimeout(1500);
check((await page.evaluate(() => window.__toasts)).some((t) => /reset EVERY AD password/.test(t)), 'teammate bulk reset toast');
const pcr = await page.evaluate(() => window.__game.scene.getScene('CcdcLab').state.engine.pcrs.filter((p) => p.breaking).map((p) => p.account).join(','));
check(pcr === 'DomainUsers,Splunk', `AD-login checks breaking (${pcr})`);
await page.screenshot({ path: `${out}/13-bulk-reset.png` });
await page.locator('.jb-tb-app[data-open="ssh-vyos"]').click();
await jump(730); await page.waitForTimeout(1500);
const vy = await page.locator('.jb-win[data-win="ssh-vyos"]').innerText();
check(vy.includes('No route to host'), 'router console taken over');
await page.screenshot({ path: `${out}/14-router-takeover.png` });
check(errors.length === 0, `no console errors ${errors.slice(0, 2).join(' | ')}`);
console.log(`${pass} passed, ${fail} failed`);
await browser.close();
process.exit(fail ? 1 : 0);
