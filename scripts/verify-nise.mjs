// NISE inject portal + incident response in the Invitational replay. node scripts/verify-nise.mjs [url] [outDir]
import { chromium } from 'playwright-core';
import fs from 'node:fs';
const url = process.argv[2] || 'http://localhost:5194/cyber-office/';
const out = process.argv[3] || 'docs/proof/nise';
fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1366, height: 800 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
let pass = 0; let fail = 0;
const check = (ok, label) => { if (ok) pass += 1; else fail += 1; console.log(`${ok ? 'PASS' : 'FAIL'} ${label}`); };
await page.goto(url + '?v=' + Date.now());
await page.waitForFunction(() => window.__game?.scene?.isActive('Title'), null, { timeout: 20000 });
await page.waitForTimeout(400); await page.keyboard.press('t');
await page.waitForFunction(() => window.__game.scene.isActive('Competitions'));
await page.locator('.comp-card[data-mode="ccdc"]').click();
await page.waitForFunction(() => window.__game.scene.isActive('CcdcLab'));
await page.locator('.ccx-radio', { hasText: 'Under Pressure' }).click();
await page.locator('.ccx-btn.primary').click();
await page.waitForSelector('.jb-taskbar');
await page.locator('.jb-tb-app[data-open="injects"]').click();
const W = page.locator('.jb-win[data-win="injects"]');
await W.locator('.nz-item').first().waitFor();
await W.locator('.nz-item[data-inject="tool23t"]').click();
const meta = await W.locator('.nz-meta').innerText();
check(/Submissions Due: (11\/14 \d+:\d\d|— \(practice)/.test(meta) && /Points Possible: \d+/.test(meta) && /TOOL23T_-_Firewall_Setup_Configuration\.pdf/.test(meta), 'inject page: due / rejected / points / PDF link');
check((await W.locator('.nz-paper').innerText()).includes('All denied packets should be logged.'), 'PDF shows the real TOOL23T text');
await page.screenshot({ path: `${out}/inject-tool23t.png` });
await W.locator('[data-f="memo"]').fill('As found, Permit Inbound and Permit Outbound allowed any to any. We added allow rules per server for web-browsing, ssl, smtp, imap, dns and WinRM 5985, applied a security profile group with anti-spyware and vulnerability protection, and logged the interzone-default deny at session end. Quotient stayed green.');
await W.locator('[data-btn="docx"]').click();
await W.locator('[data-btn="upload"]').click();
check((await W.locator('.nz-bad').innerText()).includes('Only PDF files are accepted'), '.docx upload rejected');
await W.locator('[data-btn="pdf"]').click();
await W.locator('[data-btn="upload"]').click();
check((await W.locator('.nz-sub').innerText()).includes('TOOL23T_-_Firewall_Setup_Configuration_memo.pdf submitted'), 'PDF upload accepted');
check(await page.evaluate(() => window.__game.scene.getScene('CcdcLab').state.injects.tool23t.done), 'engine recorded the submission');
await page.screenshot({ path: `${out}/inject-submitted.png` });
// Incident response
await page.evaluate(() => window.__game.scene.getScene('CcdcLab').run('ecom', 'ps -ef'));
await W.locator('.nz-tab[data-tab="ir"]').click();
await W.locator('[data-f="ir-title"]').fill('Fake scoring engine on Rocky and Ubuntu');
await W.locator('[data-host="ecom"]').check(); await W.locator('[data-host="email"]').check();
await W.locator('[data-f="ir-time"]').fill('14:31');
await W.locator('[data-f="ir-source"]').fill('/bin/scoringengine PID 7484 -> 198.51.100.45:8443');
await W.locator('[data-f="ir-description"]').fill('ps -ef showed /bin/scoringengine (PID 7484, root) parenting bash /usr/lib/.honk and the ttygoose kit.');
await W.locator('[data-f="ir-actions"]').fill('Killed 7484 and its children, removed /bin/scoringengine and /usr/lib/.honk.');
await W.locator('[data-btn="ir-submit"]').click();
check((await W.locator('.nz-irlist').innerText()).includes('Matched · 15/15'), 'incident report matched with full marks');
await page.screenshot({ path: `${out}/incident-response.png` });
check(errors.length === 0, `no console errors ${errors.slice(0, 2).join(' | ')}`);
console.log(`${pass} passed, ${fail} failed`);
await browser.close();
process.exit(fail ? 1 : 0);
